#!/usr/bin/env python3
"""The Warm ledger as the iOS app's colours (MA-165): docs/design/ds-v1/tokens.css is the one source, so the two doors
never drift. Writes an asset catalog (light, dark, increased contrast) and the Swift names for it.

  python3 scripts/ios_tokens.py          # write them
  python3 scripts/ios_tokens.py --check  # exit 1 when what is committed differs from what the tokens make

Increased contrast follows tokens.css's own rule: tertiary ink steps up to secondary; every other colour holds.
A colour this script cannot read is a failure, never a skip."""
from __future__ import annotations

import filecmp
import json
import re
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "docs/design/ds-v1/tokens.css"
PACKAGE = ROOT / "ios/Packages/MyPaisaUI/Sources/MyPaisaUI"
CATALOG = PACKAGE / "Resources/Colors.xcassets"
SWIFT = PACKAGE / "Theme/MPColor.swift"
DECLARATION = re.compile(r"--mp-([a-z0-9-]+):\s*([^;]+);")
HEX = re.compile(r"^#([0-9a-fA-F]{6})$")
RGBA = re.compile(r"^rgba\(\s*(\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\s*\)$")
# Tokens that are not a single colour: a shadow and the type stacks.
NOT_COLOURS = {"shadow", "font", "font-display", "font-num"}
HIGH_CONTRAST = {"ink-3": "ink-2"}


def block(css: str, opening: str) -> str:
    start = css.find(opening)
    if start < 0:
        raise SystemExit(f"ios_tokens: tokens.css has no block {opening!r}")
    end = css.find("\n}", start)
    if end < 0:
        raise SystemExit(f"ios_tokens: the block {opening!r} never closes")
    return css[start:end]


def colours(text: str) -> dict[str, tuple[int, int, int, float]]:
    found: dict[str, tuple[int, int, int, float]] = {}
    for name, raw in DECLARATION.findall(text):
        if name in NOT_COLOURS or name.startswith(("font", "type", "radius", "space", "ease", "dur")):
            continue
        value = raw.strip()
        if value.startswith("var("):
            continue
        if match := HEX.match(value):
            digits = match.group(1)
            found[name] = (int(digits[:2], 16), int(digits[2:4], 16), int(digits[4:], 16), 1.0)
        elif match := RGBA.match(value):
            red, green, blue, alpha = match.groups()
            found[name] = (int(red), int(green), int(blue), float(alpha))
        else:
            raise SystemExit(f"ios_tokens: --mp-{name} is in a form this script cannot read: {value}")
    return found


def swift_name(token: str) -> str:
    head, *rest = token.split("-")
    return head + "".join(part.capitalize() for part in rest)


def component(value: tuple[int, int, int, float]) -> dict[str, object]:
    red, green, blue, alpha = value
    return {
        "color": {
            "color-space": "srgb",
            "components": {
                "red": f"0x{red:02X}",
                "green": f"0x{green:02X}",
                "blue": f"0x{blue:02X}",
                "alpha": f"{alpha:.3f}",
            },
        },
        "idiom": "universal",
    }


def appearance(value: tuple[int, int, int, float], *marks: tuple[str, str]) -> dict[str, object]:
    entry = component(value)
    if marks:
        entry["appearances"] = [{"appearance": kind, "value": mark} for kind, mark in marks]
    return entry


def contents(token: str, light: dict, dark: dict) -> dict[str, object]:
    strong = HIGH_CONTRAST.get(token, token)
    return {
        "colors": [
            appearance(light[token]),
            appearance(dark[token], ("luminosity", "dark")),
            appearance(light[strong], ("contrast", "high")),
            appearance(dark[strong], ("luminosity", "dark"), ("contrast", "high")),
        ],
        "info": {"author": "xcode", "version": 1},
    }


def write(catalog: Path, swift: Path) -> None:
    css = TOKENS.read_text(encoding="utf-8")
    light = colours(block(css, ":root, .t-light {"))
    dark = {**light, **colours(block(css, ".t-dark {"))}
    missing = sorted(set(HIGH_CONTRAST) - set(light))
    if len(light) < 40 or missing:
        raise SystemExit(f"ios_tokens: tokens.css read badly: {len(light)} colours, missing {missing}")
    if catalog.exists():
        shutil.rmtree(catalog)
    catalog.mkdir(parents=True)
    (catalog / "Contents.json").write_text(
        json.dumps({"info": {"author": "xcode", "version": 1}}, indent=2) + "\n", encoding="utf-8"
    )
    for token in sorted(light):
        folder = catalog / f"{swift_name(token)}.colorset"
        folder.mkdir()
        (folder / "Contents.json").write_text(
            json.dumps(contents(token, light, dark), indent=2) + "\n", encoding="utf-8"
        )
    lines = [
        "// Generated by scripts/ios_tokens.py from docs/design/ds-v1/tokens.css. Do not edit.",
        "import SwiftUI",
        "",
        "/// The Warm ledger's colours (MA-101), each with its light, dark and increased-contrast values.",
        "public enum MPColor {",
    ]
    for token in sorted(light):
        name = swift_name(token)
        lines.append(f'  public static let {name} = Color("{name}", bundle: .module)')
    lines += ["}", ""]
    swift.parent.mkdir(parents=True, exist_ok=True)
    swift.write_text("\n".join(lines), encoding="utf-8")


def same(left: Path, right: Path) -> bool:
    compared = filecmp.dircmp(left, right)
    if compared.left_only or compared.right_only or compared.diff_files or compared.funny_files:
        return False
    return all(same(left / sub, right / sub) for sub in compared.common_dirs)


def main() -> int:
    if "--check" not in sys.argv[1:]:
        write(CATALOG, SWIFT)
        return 0
    with tempfile.TemporaryDirectory() as folder:
        catalog, swift = Path(folder) / "Colors.xcassets", Path(folder) / "MPColor.swift"
        write(catalog, swift)
        if not CATALOG.is_dir() or not same(catalog, CATALOG):
            print("ios_tokens: the colour assets are stale: run python3 scripts/ios_tokens.py", file=sys.stderr)
            return 1
        if not SWIFT.is_file() or swift.read_bytes() != SWIFT.read_bytes():
            print("ios_tokens: MPColor.swift is stale: run python3 scripts/ios_tokens.py", file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
